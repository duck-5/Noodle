export type TranslationKey = keyof typeof translations['en'];

export function getLanguage(): SupportedLanguage {
  try {
    const lang = getPreference('language');
    return lang === 'en' || lang === 'he' ? lang : 'he';
  } catch {
    return 'he';
  }
}

export function translate(
  key: TranslationKey | string,
  params?: Record<string, string | number>,
  langOverride?: SupportedLanguage
): string {
  const lang = langOverride ?? getLanguage();
  const dict = translations[lang] as Record<string, string>;
  const fallbackDict = translations.en as Record<string, string>;
  let text = dict?.[key] ?? fallbackDict?.[key] ?? String(key);
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.split(`{${k}}`).join(String(v));
    });
  }
  return text;
}

export const t = translate;
